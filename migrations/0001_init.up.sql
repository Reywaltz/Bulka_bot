-- Базовая миграция: схема бота.
--
-- tg_id — bigint: telegram id уже давно вылезают за 2^31, в integer они не влезут.
-- balance/reward_points/cost — NOT NULL DEFAULT 0: NULL там означал бы ошибку,
-- а код рассчитывает на числа.
-- Отрицательный баланс невозможен: списание идёт только при balance >= cost.

CREATE TABLE IF NOT EXISTS users (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tg_id   bigint  NOT NULL UNIQUE,
    balance integer NOT NULL DEFAULT 0 CHECK (balance >= 0)
);

CREATE TABLE IF NOT EXISTS tasks (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text          text    NOT NULL,
    completed     boolean NOT NULL DEFAULT false,
    reward_points integer NOT NULL DEFAULT 0 CHECK (reward_points >= 0)
);

CREATE TABLE IF NOT EXISTS rewards (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text    NOT NULL,
    cost integer NOT NULL DEFAULT 0 CHECK (cost >= 0)
);
